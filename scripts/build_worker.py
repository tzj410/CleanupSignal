#!/usr/bin/env python3
"""Bundle this small dependency-free Pages Worker; only local named ES module imports."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
parts=[]
parts.append(re.sub(r'\bexport (?=async |function |class |const )','',(root/'public'/'briefing-core.js').read_text()))
for name in ['security','auth','workspace','billing','alerts','worker']:
 s=(root/'server'/f'{name}.js').read_text()
 s=re.sub(r'^import .*?;\n','',s,flags=re.M)
 if name!='worker':s=re.sub(r'\bexport (?=async |function |class |const )','',s)
 parts.append('// '+name+'.js\n'+s)
(root/'public'/'_worker.js').write_text('// Generated by scripts/build_worker.py. Edit server/, then rebuild.\n'+'\n'.join(parts))
